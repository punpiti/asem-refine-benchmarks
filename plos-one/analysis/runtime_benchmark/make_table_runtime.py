"""Summarize results/runtime_results.csv into the computational-cost table.

Time = worker_method_s (method call only: excludes interpreter start-up,
imports, read simulation and evaluation). Median over the nine jobs per depth
(three pairs x three replicates), including jobs that ended without output,
whose time is the time to failure. Memory = method_peak_rss_kb, maximum over
all completed jobs of the method.

Output: plos-one/generated/tbl_runtime.tex and results/runtime_summary.csv
"""

from __future__ import annotations

import csv
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "results", "runtime_results.csv")
OUT_TEX = os.path.join(HERE, "..", "..", "generated", "tbl_runtime.tex")
OUT_CSV = os.path.join(HERE, "results", "runtime_summary.csv")
METHODS = [("ASEM", "ASEM"), ("ASEM_recursive", "ASEM (recursive)"), ("ASEM_Hybrid", "ASEM-Hybrid"),
           ("SRSC", "SRSC"), ("Pilon", "Pilon"), ("MIA", "MIA"), ("NOVOPlasty", "NOVOPlasty"),
           ("GetOrganelle", "GetOrganelle")]
DEPTHS = [1, 2, 4, 8]


def _fmt(x: float) -> str:
    return f"{x:.1f}" if x < 100 else f"{x:.0f}"


def main() -> None:
    rows = list(csv.DictReader(open(SRC, newline="")))
    summary, lines = [], [r"\begin{tabular}{lrrrrrr}", r"\toprule",
                          r"Method & 1X & 2X & 4X & 8X & Outputs & Peak RSS (MB) \\", r"\midrule"]
    for m, name in METHODS:
        mine = [r for r in rows if r["method"] == m]
        med = {d: statistics.median(float(r["worker_method_s"]) for r in mine if int(r["depth"]) == d)
               for d in DEPTHS}
        done = [r for r in mine if r["status"] == "completed"]
        rss = max(int(r["method_peak_rss_kb"]) for r in done) / 1024
        summary.append({"method": m, **{f"median_s_{d}X": round(med[d], 2) for d in DEPTHS},
                        "max_s": round(max(float(r["worker_method_s"]) for r in mine), 1),
                        "n_completed": len(done), "n_jobs": len(mine), "max_method_rss_mb": round(rss)})
        lines.append(f"{name} & " + " & ".join(_fmt(med[d]) for d in DEPTHS)
                     + f" & {len(done)}/{len(mine)} & {rss:.0f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(OUT_TEX), exist_ok=True)
    with open(OUT_TEX, "w") as fh:
        fh.write("% Generated by plos-one/analysis/runtime_benchmark/make_table_runtime.py; do not edit.\n")
        fh.write("\n".join(lines) + "\n")
    with open(OUT_CSV, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(summary[0]))
        w.writeheader()
        w.writerows(summary)
    for s in summary:
        print(s)


if __name__ == "__main__":
    main()
