"""Read-length table (mean F1 per method, divergence and length condition at 4X).

Source: results/results.csv. Rows for MIA, Pilon and NOVOPlasty are replaced
by the N-safe rerun (../evaluator_n_fix/results/read_length.csv) when it is
complete, so every value uses the corrected evaluator. Writes
plos-one/generated/tbl_read_length.tex and results/read_length_summary.csv.
"""

from __future__ import annotations

import csv
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "results", "results.csv")
FIXED = os.path.join(HERE, "..", "evaluator_n_fix", "results", "read_length.csv")
OUT_TEX = os.path.join(HERE, "..", "..", "generated", "tbl_read_length.tex")
OUT_CSV = os.path.join(HERE, "results", "read_length_summary.csv")
METHODS = [("ASEM", "ASEM"), ("ASEM_Hybrid", "ASEM-Hybrid"), ("SRSC", "SRSC"), ("Pilon", "Pilon"), ("MIA", "MIA")]
TIERS = [("same-genus", "same genus"), ("same-family", "same family"), ("same-order", "same order")]
LENGTHS = ["50", "75", "100", "150", "250", "300", "variable"]


def load() -> list[dict]:
    rows = list(csv.DictReader(open(SRC, newline="")))
    if os.path.exists(FIXED):
        fixed = list(csv.DictReader(open(FIXED, newline="")))
        replaced = {r["method"] for r in fixed}
        if len(fixed) == 63 * len(replaced):
            rows = [r for r in rows if r["method"] not in replaced] + fixed
        else:
            print(f"N-safe rerun incomplete ({len(fixed)} rows); using original rows")
    return rows


def main() -> None:
    rows = load()
    cell = {}
    for r in rows:
        cell.setdefault((r["method"], r["divergence"], r["length_condition"]), []).append(r)
    summary = []
    lines = [r"\begin{tabular}{ll" + "r" * len(LENGTHS) + "}", r"\toprule",
             "Method & Divergence & " + " & ".join(f"{l} bp" if l != "variable" else "variable" for l in LENGTHS)
             + r" \\", r"\midrule"]
    for m_i, (m, name) in enumerate(METHODS):
        for t_i, (tier, label) in enumerate(TIERS):
            cells = []
            for length in LENGTHS:
                rs = cell.get((m, tier, length), [])
                ok = [r for r in rs if r["status"] == "completed"]
                f1 = statistics.mean(float(r["f1"]) for r in ok) if ok else None
                idv = statistics.mean(float(r["identity_pct"]) for r in ok) if ok else None
                summary.append({"method": m, "divergence": tier, "length_condition": length,
                                "n_completed": len(ok), "n_jobs": len(rs),
                                "f1_mean": f1 if f1 is None else round(f1, 6),
                                "f1_min": min((float(r["f1"]) for r in ok), default=None),
                                "f1_max": max((float(r["f1"]) for r in ok), default=None),
                                "identity_mean": idv if idv is None else round(idv, 4)})
                text = "--" if f1 is None else f"{f1:.4f}"
                if ok and len(ok) < len(rs):
                    text += rf"$^{{{len(ok)}/{len(rs)}}}$"
                cells.append(text)
            lines.append((name if t_i == 0 else "") + f" & {label} & " + " & ".join(cells) + r" \\")
        if m_i < len(METHODS) - 1:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(OUT_TEX), exist_ok=True)
    with open(OUT_TEX, "w") as fh:
        fh.write("% Generated by plos-one/analysis/read_length_all_methods/make_table_read_length.py; do not edit.\n")
        fh.write("\n".join(lines) + "\n")
    with open(OUT_CSV, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(summary[0]))
        w.writeheader()
        w.writerows(summary)
    print("wrote", os.path.abspath(OUT_TEX))


if __name__ == "__main__":
    main()
