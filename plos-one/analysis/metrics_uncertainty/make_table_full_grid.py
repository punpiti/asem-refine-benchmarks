"""Write the reference-guided full-grid table (F1 and identity) from results/accuracy_by_cell.csv,
plus a pooled 1-8X column (mean over all completed jobs at 1-8X, from summarize_main_grid.load).

Output: plos-one/generated/tbl_full_grid_guided.tex (input by 03c-external-tools-table.tex).
Bold = highest mean F1 (within 0.001) or identity (within 0.1 points) in each divergence/depth,
not marked in the same-genus block where every method is at ceiling.
"""

from __future__ import annotations

import csv
import os
import statistics as st

from summarize_main_grid import load

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "results", "accuracy_by_cell.csv")
STATUS = os.path.join(HERE, "results", "status_by_cell.csv")
OUT = os.path.join(HERE, "..", "..", "generated", "tbl_full_grid_guided.tex")

METHODS = [("ASEM", "ASEM"), ("ASEM_Hybrid", "ASEM-Hybrid"), ("SRSC", "SRSC"), ("Pilon", "Pilon"), ("MIA", "MIA")]
TIERS = [("same-genus", "same genus"), ("same-family", "same family"), ("same-order", "same order")]
DEPTHS = ["1", "2", "4", "8"]
POOLED = "1--8"


def main() -> None:
    acc = {(r["divergence"], r["depth"], r["method"]): r for r in csv.DictReader(open(SRC, newline=""))}
    status = {(r["divergence"], r["depth"], r["method"]): r for r in csv.DictReader(open(STATUS, newline=""))}
    for m, _ in METHODS:
        jobs = load(m)
        for tier, _ in TIERS:
            done = [j for j in jobs.values() if j["divergence"] == tier and j["status"] == "completed"]
            acc[(tier, POOLED, m)] = {"f1_mean": st.mean(j["f1"] for j in done),
                                      "identity_mean": st.mean(j["identity"] for j in done)}
            status[(tier, POOLED, m)] = {"n_completed": str(len(done)),
                                         "n_jobs": str(sum(j["divergence"] == tier for j in jobs.values()))}
    cols = DEPTHS + [POOLED]
    lines = [r"\begin{tabular}{ll" + "rr" * len(cols) + "}", r"\toprule",
             " & & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{d}X{' (pooled)' if d == POOLED else ''}}}" for d in cols) + r" \\",
             "".join(rf"\cmidrule(lr){{{3 + 2 * i}-{4 + 2 * i}}}" for i in range(len(cols))),
             "Divergence & Method & " + " & ".join(["F1 & Id. (\\%)"] * len(cols)) + r" \\", r"\midrule"]
    for t_i, (tier, label) in enumerate(TIERS):
        best = {}
        for d in cols:
            f1s = [float(acc[(tier, d, m)]["f1_mean"]) for m, _ in METHODS]
            ids = [float(acc[(tier, d, m)]["identity_mean"]) for m, _ in METHODS]
            best[d] = (max(f1s), max(ids))
        for m_i, (m, name) in enumerate(METHODS):
            cells = []
            for d in cols:
                r = acc[(tier, d, m)]
                f1, idv = float(r["f1_mean"]), float(r["identity_mean"])
                mark = tier != "same-genus"
                f1s = f"{f1:.4f}"
                ids = f"{idv:.2f}"
                if mark and f1 >= best[d][0] - 0.001:
                    f1s = rf"\textbf{{{f1s}}}"
                if mark and idv >= best[d][1] - 0.1:
                    ids = rf"\textbf{{{ids}}}"
                cells += [f1s, ids]
            lines.append((label if m_i == 0 else "") + f" & {name} & " + " & ".join(cells) + r" \\")
        out = [f"{status[(tier, d, 'MIA')].get('n_completed', '0')}/{status[(tier, d, 'MIA')]['n_jobs']}" for d in cols]
        lines.append(r" & \quad MIA outputs & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{o}}}" for o in out) + r" \\")
        if t_i < len(TIERS) - 1:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("% Generated by plos-one/analysis/metrics_uncertainty/make_table_full_grid.py; do not edit.\n")
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.abspath(OUT))


if __name__ == "__main__":
    main()
